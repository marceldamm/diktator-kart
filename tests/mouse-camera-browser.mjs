import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { send, evaluate, delay, load, tap, key, errors, socket } from './cdp.mjs';
const move = (x,y,buttons=0) => send('Input.dispatchMouseEvent',{type:'mouseMoved',x,y,buttons,button:buttons&1?'left':buttons&2?'right':'none'});
const button = (type,x,y,which='left',buttons=type==='mousePressed'?1:0) => send('Input.dispatchMouseEvent',{type,x,y,button:which,buttons,clickCount:1});
const snapshot = () => evaluate(`({view:window.__DK.view,state:window.__DK.state,menu:window.__DK.menu,yaw:window.__DK.scene.activeCamera.rotation.y,heading:window.__DK.kart.heading,drag:document.querySelector('#render-canvas').classList.contains('camera-dragging'),locked:document.pointerLockElement===document.querySelector('#render-canvas'),debug:document.querySelector('#debug').textContent})`);
const waitLock = async active => { for(let i=0;i<40;i++){if((await snapshot()).locked===active)return;await delay(50);}throw Error('Pointer Lock did not '+(active?'activate':'release')); };
const angle = (a,b) => Math.abs(Math.atan2(Math.sin(a-b),Math.cos(a-b)));
const evidence=[];
try {
  await send('Runtime.enable');
  await send('Page.bringToFront');
  await send('Emulation.setFocusEmulationEnabled',{enabled:true});
  await send('Emulation.setDeviceMetricsOverride',{width:1280,height:800,deviceScaleFactor:1,mobile:false});
  await load('?fleet=1');
  await button('mousePressed',900,450); await move(1080,440,1);
  assert.equal((await snapshot()).drag,false,'Menu must not capture camera input');
  await button('mouseReleased',1080,440);
  await evaluate(`document.querySelector('#menu-practice').click();document.querySelector('#debug').hidden=false`);
  await delay(600);
  for (let i=0;i<3;i++) {
    const base=await snapshot();
    await move(400,350); await move(650,390); await delay(250);
    const hover=await snapshot(); assert.ok(angle(hover.yaw,base.yaw)<.015,'Hover changed camera');
    assert.equal(await evaluate(`document.elementFromPoint(400,350).id`),'render-canvas');
    await button('mousePressed',400,350); await waitLock(true); await move(560,390,1); await delay(400);
    const drag=await snapshot(); assert.equal(drag.drag,true); assert.ok(angle(drag.yaw,base.yaw)>.2,'Held drag did not turn camera');
    assert.ok(!drag.debug.includes('Letzte Aktion: Item-Eingabe erkannt'),'Camera gesture must not use an item');
    await delay(2200);
    const held=await snapshot(); assert.ok(angle(held.yaw,base.yaw)>.2,'Held view should remain steady, not auto-centre');
    await button('mouseReleased',560,390); await waitLock(false); await delay(1400);
    const released=await snapshot(); assert.equal(released.drag,false); assert.ok(angle(released.yaw,base.yaw)<.04,'Release did not softly centre');
    await move(650,390); await delay(150); assert.ok(angle((await snapshot()).yaw,released.yaw)<.02);
    await button('mousePressed',400,350,'right',2); await waitLock(true); await delay(160);
    const rear=await snapshot(); assert.ok(angle(rear.yaw,base.yaw)>2.5,'X must show rear');
    await button('mouseReleased',400,350,'right',0); await waitLock(false); await delay(900);
    assert.ok(angle((await snapshot()).yaw,base.yaw)<.04,'Rear must release');
    evidence.push({view:base.view,hover:angle(hover.yaw,base.yaw),held:angle(held.yaw,base.yaw),centred:angle(released.yaw,base.yaw),rear:angle(rear.yaw,base.yaw)});
    await tap('c','KeyC',67); await delay(300);
  }
  await button('mousePressed',400,350); await waitLock(true); await move(560,390,1);
  await tap('Escape','Escape',27); assert.equal((await snapshot()).drag,false,'Menu entry must release capture');
  await button('mouseReleased',560,390);
  await evaluate(`document.querySelector('#menu-practice').click()`); await delay(300);
  await button('mousePressed',400,350); await waitLock(true); await move(560,390,1);
  await evaluate(`window.dispatchEvent(new Event('blur'))`); assert.equal((await snapshot()).drag,false,'Focus loss must release capture');
  await button('mouseReleased',560,390);
  await delay(1300);
  await tap('e','KeyE',69); await delay(400);
  assert.ok((await snapshot()).debug.includes('Letzte Aktion: Item-Eingabe erkannt'),'E must remain item input');
  assert.equal(await evaluate(`document.pointerLockElement===null`),true,'No permanent pointer lock');
  assert.deepEqual(errors,[]);
  await writeFile('docs/evidence/mouse-camera-final-check.json',JSON.stringify({controls:'LMB hold free look; RMB/X hold rear; E item; temporary native Pointer Lock only while held',viewport:'1280x800',fleet:1,evidence,menuAndFocusRelease:true,itemSeparate:true,runtimeErrors:errors},null,2)+'\n');
  console.log('PASS: all three views hover/left-look/held/release/right-rear; menu, focus loss, E item; native cursor lock released.');
} finally { socket.close(); }
